  Widget _buildTextField(
    String label,
    String key,
    String hint,
    bool isDark, {
    TextInputType? keyboardType,
    bool isReadOnly = false,
  }) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(
          label.toUpperCase(),
          style: DesignSystem.text(
            fontSize: 10,
            fontWeight: FontWeight.w800,
            letterSpacing: 1.0,
            color: isDark ? Colors.white.withValues(alpha: 0.6) : Colors.grey[600],
          ),
        ),
        const SizedBox(height: 8),
        TextFormField(
          initialValue: _formData[key].toString(),
          readOnly: isReadOnly,
          keyboardType: keyboardType,
          decoration: InputDecoration(
            hintText: hint,
            border: OutlineInputBorder(
              borderRadius: BorderRadius.circular(12),
            ),
          ),
          onChanged: (value) {
            setState(() {
              _formData[key] = value;
              if (key == 'source_resource') {
                _isBatchAutoGenerated = false;
              }
            });
          },
          validator: (value) {
            if (key == 'source_resource') return null; // Optional
            if (value == null || value.isEmpty) {
              return '$label is required';
            }
            if ((key == 'quantity_purchased' || key == 'unit_price') &&
                double.tryParse(value) == null) {
              return 'Invalid number';
            }
            return null;
          },
        ),
      ],
    );
  }

  Widget _buildDropdown(
    String label,
    String key,
    List<String> options,
    bool isDark, {
    bool isLocked = false,
  }) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(
          label.toUpperCase(),
          style: DesignSystem.text(
            fontSize: 10,
            fontWeight: FontWeight.w800,
            letterSpacing: 1.0,
            color: isDark ? Colors.white.withValues(alpha: 0.6) : Colors.grey[600],
          ),
        ),
        const SizedBox(height: 8),
        DropdownButtonFormField<String>(
          initialValue: _formData[key].toString(),
          decoration: InputDecoration(
            border: OutlineInputBorder(
              borderRadius: BorderRadius.circular(12),
            ),
          ),
          items: options
              .map((option) => DropdownMenuItem(
                    value: option,
                    child: Text(option),
                  ))
              .toList(),
          onChanged: isLocked
              ? null
              : (value) {
                  if (value != null) {
                    setState(() {
                      _formData[key] = value;
                    });
                  }
                },
        ),
        if (isLocked)
          Padding(
            padding: const EdgeInsets.only(top: 4, left: 4),
            child: Text(
              _currentQueueIndex != -1
                  ? 'Sequential category locked'
                  : 'Locked to current view',
              style: DesignSystem.text(
                fontSize: 10,
                fontWeight: FontWeight.bold,
                color: AppConstants.limeGreen,
              ).copyWith(fontStyle: FontStyle.italic),
            ),
          ),
      ],
    );
  }

  Widget _buildDateField(String label, String key, bool isDark) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(
          label.toUpperCase(),
          style: DesignSystem.text(
            fontSize: 10,
            fontWeight: FontWeight.w800,
            letterSpacing: 1.0,
            color: isDark ? Colors.white.withValues(alpha: 0.6) : Colors.grey[600],
          ),
        ),
        const SizedBox(height: 8),
        InkWell(
          onTap: () async {
            final date = await showDatePicker(
              context: context,
              initialDate: DateTime.now(),
              firstDate: DateTime(2020),
              lastDate: DateTime.now(),
            );
            if (date != null) {
              setState(() {
                _formData[key] =
                    '${date.year}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')}';
              });
            }
          },
          child: Container(
            padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 14),
            decoration: BoxDecoration(
              border: Border.all(
                color: isDark
                    ? Colors.white.withValues(alpha: 0.3)
                    : Colors.grey[400]!,
              ),
              borderRadius: BorderRadius.circular(12),
            ),
            child: Row(
              children: [
                Icon(Icons.calendar_today, size: 18, color: AppConstants.limeGreen),
                const SizedBox(width: 12),
                Text(
                  _formData[key].toString(),
                  style: DesignSystem.text(
                    fontSize: 14,
                    fontWeight: FontWeight.bold,
                    color: isDark ? Colors.white : Colors.black87,
                  ),
                ),
              ],
            ),
          ),
        ),
      ],
    );
  }
