  Widget _buildCategoryGrid(InventoryProvider provider) {
    final categoryStats = provider.getCategoryStats();

    return LayoutBuilder(
      builder: (context, constraints) {
        final crossAxisCount = constraints.maxWidth > 1200
            ? 4
            : constraints.maxWidth > 900
                ? 3
                : constraints.maxWidth > 600
                    ? 2
                    : 1;

        return GridView.builder(
          shrinkWrap: true,
          physics: const NeverScrollableScrollPhysics(),
          gridDelegate: SliverGridDelegateWithFixedCrossAxisCount(
            crossAxisCount: crossAxisCount,
            childAspectRatio: 1.2,
            crossAxisSpacing: 16,
            mainAxisSpacing: 16,
          ),
          itemCount: _categoryConfig.length,
          itemBuilder: (context, index) {
            final category = _categoryConfig.keys.elementAt(index);
            final config = _categoryConfig[category]!;
            final stats = categoryStats[category]!;

            return InventoryStatCard(
              icon: config.icon,
              iconColor: config.color,
              bgColor: config.bgColor,
              category: category,
              itemCount: stats.itemCount,
              totalQuantity: stats.totalQuantity,
              onTap: () {
                setState(() {
                  _selectedCategory = category;
                });
              },
            );
          },
        );
      },
    );
  }

  Widget _buildItemsList(InventoryProvider provider) {
    final isDark = Theme.of(context).brightness == Brightness.dark;

    final filteredItems = provider.items.where((item) {
      final matchesCategory = item.category == _selectedCategory;
      final matchesSearch = _searchQuery.isEmpty ||
          item.itemName.toLowerCase().contains(_searchQuery.toLowerCase()) ||
          (item.sourceResource?.toLowerCase().contains(_searchQuery.toLowerCase()) ?? false);
      return matchesCategory && matchesSearch;
    }).toList();

    if (filteredItems.isEmpty) {
      return _buildEmptyState(isDark);
    }

    return Column(
      children: [
        // Search bar
        Padding(
          padding: const EdgeInsets.only(bottom: 16),
          child: TextField(
            decoration: InputDecoration(
              hintText: 'Search items...',
              prefixIcon: Icon(Icons.search, color: AppConstants.limeGreen),
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(12),
              ),
            ),
            onChanged: (value) {
              setState(() {
                _searchQuery = value;
              });
            },
          ),
        ),

        // Items list
        ListView.separated(
          shrinkWrap: true,
          physics: const NeverScrollableScrollPhysics(),
          itemCount: filteredItems.length,
          separatorBuilder: (context, index) => const SizedBox(height: 16),
          itemBuilder: (context, index) {
            final item = filteredItems[index];
            return _buildItemCard(item, isDark);
          },
        ),
      ],
    );
  }

