  String _getTodayDate() {
    final now = DateTime.now();
    return '${now.year}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';
  }

  Future<void> _loadToken() async {
    _authToken = await _secureStorage.getAuthToken();
    if (_authToken != null && mounted) {
      final inventoryProvider =
          Provider.of<InventoryProvider>(context, listen: false);
      await inventoryProvider.fetchInventory(_authToken!);
    }
  }

  Future<void> _handleRefresh() async {
    if (_authToken != null) {
      final inventoryProvider =
          Provider.of<InventoryProvider>(context, listen: false);
      await inventoryProvider.fetchInventory(_authToken!);
    }
  }

  void _handleAddNew() {
    _isBatchAutoGenerated = true;
    if (_selectedCategory != null) {
      _showModeSelectionDialog();
    } else {
      _openFormWithCategory(_categoryConfig.keys.first);
    }
  }

  void _showModeSelectionDialog() {
    showDialog(
      context: context,
      builder: (context) => BatchRegistrationModal(
        selectedCategory: _selectedCategory!,
        onSingleMode: () {
          _openFormWithCategory(_selectedCategory!);
        },
        onBatchMode: (categories, batchName) {
          _startBatchRegistration(categories, batchName);
        },
      ),
    );
  }

  void _openFormWithCategory(String category, [String batchName = '']) {
    setState(() {
      _formData['item_name'] = '';
      _formData['category'] = category;
      _formData['inventory_type'] = 'Consumable';
      _formData['source_resource'] = batchName;
      _formData['quantity_purchased'] = '';
      _formData['unit'] = 'units';
      _formData['unit_price'] = '';
      _formData['purchase_date'] = _getTodayDate();
      _editingId = null;
      _showForm = true;
    });
  }

  void _startBatchRegistration(List<String> categories, String batchName) {
    final queue = [_selectedCategory!, ...categories];
    setState(() {
      _batchQueue = queue;
      _currentQueueIndex = 0;
      _globalBatchName = batchName;
    });
    _openFormWithCategory(queue[0], batchName);
  }

  void _closeForm() {
    setState(() {
      _showForm = false;
      _batchQueue = [];
      _currentQueueIndex = -1;
      _globalBatchName = '';
    });
  }

  void _handleEdit(InventoryItem item) {
    _isBatchAutoGenerated = false;
    setState(() {
      _formData['item_name'] = item.itemName;
      _formData['category'] = item.category;
      _formData['inventory_type'] = item.inventoryType;
      _formData['source_resource'] = item.sourceResource ?? '';
      _formData['quantity_purchased'] = item.quantityPurchased.toString();
      _formData['unit'] = item.unit;
      _formData['unit_price'] = item.unitPrice.toString();
      _formData['purchase_date'] = item.purchaseDate;
      _editingId = item.id;
      _showForm = true;
    });
  }

  Future<void> _handleSubmit() async {
    if (!_formKey.currentState!.validate()) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('Please fill all required fields'),
          backgroundColor: Colors.orange,
        ),
      );
      return;
    }

    if (_authToken == null) return;

    final inventoryProvider =
        Provider.of<InventoryProvider>(context, listen: false);

    bool success;
    if (_editingId != null) {
      // Update existing item
      success = await inventoryProvider.updateItem(
        token: _authToken!,
        id: _editingId!,
        itemName: _formData['item_name'],
        category: _formData['category'],
        inventoryType: _formData['inventory_type'],
        sourceResource: _formData['source_resource'].isEmpty
            ? null
            : _formData['source_resource'],
        quantityPurchased: int.parse(_formData['quantity_purchased']),
        quantityAvailable: int.parse(_formData['quantity_purchased']),
        unit: _formData['unit'],
        unitPrice: double.parse(_formData['unit_price']),
        purchaseDate: _formData['purchase_date'],
      );
    } else {
      // Create new item
      success = await inventoryProvider.createItem(
        token: _authToken!,
        itemName: _formData['item_name'],
        category: _formData['category'],
        inventoryType: _formData['inventory_type'],
        sourceResource: _formData['source_resource'].isEmpty
            ? null
            : _formData['source_resource'],
        quantityPurchased: int.parse(_formData['quantity_purchased']),
        unit: _formData['unit'],
        unitPrice: double.parse(_formData['unit_price']),
        purchaseDate: _formData['purchase_date'],
      );
    }

    if (mounted) {
      if (success) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(_editingId != null
                ? 'Item updated successfully'
                : 'Item created successfully'),
            backgroundColor: AppConstants.forestGreen,
          ),
        );

        // Handle sequential batch registration
        if (_currentQueueIndex != -1 &&
            _currentQueueIndex < _batchQueue.length - 1) {
          final nextIndex = _currentQueueIndex + 1;
          setState(() {
            _currentQueueIndex = nextIndex;
            _selectedCategory = _batchQueue[nextIndex];
          });
          _openFormWithCategory(_batchQueue[nextIndex], _globalBatchName);
        } else {
          _closeForm();
        }
      } else {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(inventoryProvider.error ?? 'Failed to save item'),
            backgroundColor: Colors.red,
          ),
        );
      }
    }
  }

  Future<void> _handleDelete(int id, String itemName) async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        title: Text(
          'Delete Item',
          style: DesignSystem.heading(fontWeight: FontWeight.w600),
        ),
        content: Text(
          'Are you sure you want to delete "$itemName"?',
          style: DesignSystem.text(),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: Text('Cancel', style: DesignSystem.text()),
          ),
          TextButton(
            onPressed: () => Navigator.pop(context, true),
            style: TextButton.styleFrom(foregroundColor: Colors.red),
            child: Text('Delete', style: DesignSystem.text()),
          ),
        ],
      ),
    );

    if (confirmed == true && _authToken != null && mounted) {
      final inventoryProvider =
          Provider.of<InventoryProvider>(context, listen: false);
      final success = await inventoryProvider.deleteItem(
        token: _authToken!,
        id: id,
      );

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(success
                ? 'Item deleted successfully'
                : inventoryProvider.error ?? 'Failed to delete item'),
            backgroundColor: success ? AppConstants.forestGreen : Colors.red,
          ),
        );
      }
    }
  }

  String _generateBatchNumber() {
    if (_editingId != null ||
        !_isBatchAutoGenerated ||
        _formData['category'].isEmpty ||
        _formData['item_name'].isEmpty ||
        _formData['purchase_date'].isEmpty) {
      return _formData['source_resource'];
    }

    final inventoryProvider =
        Provider.of<InventoryProvider>(context, listen: false);
    final existingItems = inventoryProvider.items;

    // Type prefix
    String typePrefix;
    if (_formData['category'] == 'Fertilizer') {
      typePrefix = 'FER';
    } else if (_formData['category'] == 'Pesticides') {
      typePrefix = 'PES';
    } else if (_formData['category'] == 'Fungicides') {
      typePrefix = 'FUN';
    } else {
      typePrefix = _formData['category']
          .toString()
          .substring(0, min(3, _formData['category'].toString().length))
          .toUpperCase();
    }

    // Name prefix (first 4 chars)
    final itemName = _formData['item_name'].toString().replaceAll(' ', '');
    final namePrefix =
        itemName.substring(0, min(4, itemName.length)).toUpperCase();

    // Date prefix (DDMM)
    final dateParts = _formData['purchase_date'].toString().split('-');
    if (dateParts.length != 3) return _formData['source_resource'];
    final datePrefix = '${dateParts[2]}${dateParts[1]}';

    final basePrefix = '$typePrefix-$namePrefix-$datePrefix';

    // Find max sequence
    final matchingItems = existingItems
        .where((item) =>
            item.sourceResource != null &&
            item.sourceResource!.startsWith(basePrefix))
        .toList();

    int nextSeq = 1;
    if (matchingItems.isNotEmpty) {
      final sequences = matchingItems
          .map((item) {
            final parts = item.sourceResource!.split('-');
            if (parts.length >= 4) {
              return int.tryParse(parts[3]) ?? 0;
            }
            return 0;
          })
          .where((seq) => seq > 0)
          .toList();

      if (sequences.isNotEmpty) {
        nextSeq = sequences.reduce(max) + 1;
      }
    }

    final seqPart = nextSeq.toString().padLeft(3, '0');
    final sameSuffix = _currentQueueIndex != -1 ? '-SAME' : '';

    return '$basePrefix-$seqPart$sameSuffix';
  }

